using System.Globalization;
using System.Text.RegularExpressions;
using System.Xml;

namespace CanClient.Core.ModelMatching;

/// <summary>
/// 一条模型匹配规则，vPilot 的 ModelMatchRule。和 .vmr 文件里的属性一一对应：
///
///     &lt;ModelMatchRule CallsignPrefix="CCA" TypeCode="B738" ModelName="FSLTL_B738_CCA//FSLTL_B738_CCA2" /&gt;
///
/// ModelName 里可以用 // 分隔多个候选，匹配时随机挑一个（或沿用上次挑中的那个）。
/// </summary>
public sealed class ModelMatchRule
{
    public const string ModelDelimiter = "//";
    public const string AutoGenerated = "AutoGenerated";

    public string? Callsign { get; set; }
    public string? CallsignPrefix { get; set; }
    public string? TypeCode { get; set; }
    public string ModelName { get; set; } = "";
    public string? FlightNumberRange { get; set; }
    public int MinFlightNumber { get; set; }
    public int MaxFlightNumber { get; set; }
    /// <summary>规则来自哪个文件；自动生成的是 "AutoGenerated"。</summary>
    public string SourceFilePath { get; set; } = "";

    public bool IsCallsignSpecific => !string.IsNullOrEmpty(Callsign) || !string.IsNullOrEmpty(CallsignPrefix);

    public IEnumerable<string> Models() =>
        ModelName.Split(ModelDelimiter, StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);

    public override string ToString()
    {
        var who = !string.IsNullOrEmpty(Callsign) ? Callsign
            : !string.IsNullOrEmpty(CallsignPrefix) ? CallsignPrefix + "*" : "任意航司";
        var range = string.IsNullOrEmpty(FlightNumberRange) ? "" : $" 航班号 {FlightNumberRange}";
        return $"{who} / {(string.IsNullOrEmpty(TypeCode) ? "任意机型" : TypeCode)}{range}";
    }
}

/// <summary>
/// 一个 .vmr 规则集，vPilot 的 ModelMatchRuleSet。只读不写——自定义规则集是用户或 AI 包作者
/// 维护的文件，客户端不去改它。
/// </summary>
public sealed class ModelMatchRuleSet : List<ModelMatchRule>
{
    private static readonly Regex RangePattern = new(@"^(\d+)\-(\d+)$", RegexOptions.Compiled);

    public string? Folder { get; set; }
    public DateTime? UpdatedOn { get; set; }
    public string? Path { get; set; }

    /// <summary>
    /// 读一个 .vmr。和 vPilot 的 ReadXml 一样逐个元素读属性，不走 XmlSerializer：
    /// 真实文件里属性名周围常有空格（TypeCode = "A19N"），Folder/UpdatedOn 也经常缺。
    /// </summary>
    public static ModelMatchRuleSet Load(string path)
    {
        using var stream = File.OpenRead(path);
        var set = Load(stream);
        set.Path = path;
        foreach (var rule in set)
            rule.SourceFilePath = path;
        return set;
    }

    public static ModelMatchRuleSet Load(Stream stream)
    {
        var set = new ModelMatchRuleSet();
        var settings = new XmlReaderSettings
        {
            IgnoreWhitespace = true,
            IgnoreComments = true,
            DtdProcessing = DtdProcessing.Ignore,
            CheckCharacters = false
        };
        using var reader = XmlReader.Create(stream, settings);
        while (reader.Read())
        {
            if (reader.NodeType != XmlNodeType.Element)
                continue;
            if (reader.LocalName == "ModelMatchRuleSet")
            {
                set.Folder = reader.GetAttribute("Folder");
                var updated = reader.GetAttribute("UpdatedOn");
                if (!string.IsNullOrEmpty(updated) && DateTime.TryParseExact(updated, "M/d/yyyy h:mm:ss tt",
                        CultureInfo.InvariantCulture, DateTimeStyles.None, out var when))
                    set.UpdatedOn = when;
                continue;
            }
            if (reader.LocalName != "ModelMatchRule")
                continue;

            var rule = new ModelMatchRule
            {
                CallsignPrefix = Clean(reader.GetAttribute("CallsignPrefix")),
                FlightNumberRange = Clean(reader.GetAttribute("FlightNumberRange")),
                Callsign = Clean(reader.GetAttribute("Callsign")),
                TypeCode = Clean(reader.GetAttribute("TypeCode")),
                ModelName = reader.GetAttribute("ModelName")?.Trim() ?? ""
            };
            if (!string.IsNullOrEmpty(rule.FlightNumberRange))
            {
                var match = RangePattern.Match(rule.FlightNumberRange);
                if (match.Success)
                {
                    rule.MinFlightNumber = int.Parse(match.Groups[1].Value, CultureInfo.InvariantCulture);
                    rule.MaxFlightNumber = int.Parse(match.Groups[2].Value, CultureInfo.InvariantCulture);
                }
            }
            if (rule.ModelName.Length > 0)
                set.Add(rule);
        }
        return set;
    }

    private static string? Clean(string? value)
    {
        value = value?.Trim();
        return string.IsNullOrEmpty(value) ? null : value.ToUpperInvariant();
    }
}
