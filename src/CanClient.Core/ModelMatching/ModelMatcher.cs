using System.Text.RegularExpressions;
using CanClient.Core.Util;

namespace CanClient.Core.ModelMatching;

/// <summary>一次匹配的结果：用哪个模型、哪条规则、第几轮命中的。</summary>
public sealed record ModelMatchResult(string ModelName, ModelMatchRule? Rule, int Pass, string TypeCode)
{
    public bool IsDefault => Rule is null;

    /// <summary>界面上"匹配方式"那一列。</summary>
    public string Description => Pass switch
    {
        1 => "航司 + 机型",
        2 => $"航司 + 同族机型 {Rule?.TypeCode}",
        3 => "机型（任意涂装）",
        4 => $"同族机型 {Rule?.TypeCode}（任意涂装）",
        _ => "默认模型（没有合适的模型）"
    };

    /// <summary>规则来自哪里：自定义规则集的文件名、自动生成、内置。</summary>
    public string Source
    {
        get
        {
            if (Rule is null)
                return "默认";
            if (Rule.SourceFilePath == ModelMatchRule.AutoGenerated)
                return "自动生成";
            if (Rule.SourceFilePath == ModelMatcher.BuiltInSource)
                return "内置";
            return Path.GetFileName(Rule.SourceFilePath);
        }
    }
}

/// <summary>一个自定义规则集的加载结果，设置页显示用。</summary>
public sealed record RuleSetStatus(string Path, int RuleCount, string? Error);

/// <summary>
/// 模型匹配，vPilot Type_0200008A。规则有三个来源，按这个顺序参与匹配：
///
///   1. 自定义规则集（.vmr，按设置里的顺序）——FSLTL、AIG 这些 AI 包自带的就是这种；
///   2. 自动生成的规则——扫描到的每个已识别涂装按 (机型, 航司) 归组，包的优先级决定先后；
///   3. 内置规则——默认机（MSFS 2020 的 Generic Airliner、2024 的 PassiveAircraft）。
///
/// 匹配分四轮，每一轮按上面的顺序把所有规则走一遍，第一条命中的就用：
///
///   第 1 轮  带航司的规则，机型完全一致
///   第 2 轮  带航司的规则，同族机型（SimilarTypeCodes）
///   第 3 轮  不带航司的规则，机型完全一致
///   第 4 轮  不带航司的规则，同族机型
///
/// 都没有就用默认模型。航司条件还可以按航班号范围限定（FlightNumberRange="1000-1999"）。
/// 模拟器拒绝生成过的模型记进 <see cref="ErroneousModels"/>，之后的匹配跳过它们。
/// </summary>
public sealed class ModelMatcher
{
    public const string BuiltInSource = "BuiltIn";

    private static readonly Logger Log = Util.Log.For("matching");
    private static readonly Regex FlightNumber = new(@"^[A-Z]+(\d+)[A-Z]?$", RegexOptions.IgnoreCase | RegexOptions.Compiled);

    // MSFS 2024 的被动 AI 机是流式下载的，扫描不到，但一定可用（vPilot 也是这么写死的）
    private static readonly HashSet<string> Msfs2024PassiveAircraft = new(
        BuiltInRules.Msfs2024.SelectMany(r => r.ModelName.Split(ModelMatchRule.ModelDelimiter)),
        StringComparer.OrdinalIgnoreCase);

    private readonly object _sync = new();
    private IReadOnlyList<ModelMatchRule> _customRules = [];
    private IReadOnlyList<ModelMatchRule> _generatedRules = [];
    private IReadOnlyList<RuleSetStatus> _ruleSetStatus = [];
    private HashSet<string> _installedTitles = new(StringComparer.OrdinalIgnoreCase);
    private readonly HashSet<string> _erroneous = new(StringComparer.OrdinalIgnoreCase);

    public ModelMatcher(ModelMatchingData data)
    {
        Data = data;
    }

    public ModelMatchingData Data { get; private set; }

    public SimulatorType Simulator { get; private set; } = SimulatorType.None;

    public string DefaultModel { get; set; } = SimulatorType.Msfs.DefaultModel();

    public IReadOnlyList<ModelMatchRule> CustomRules => _customRules;
    public IReadOnlyList<ModelMatchRule> GeneratedRules => _generatedRules;
    public IReadOnlyList<RuleSetStatus> RuleSetStatus => _ruleSetStatus;

    /// <summary>规则或扫描结果变了。界面和已经在天上的飞机据此重新匹配。</summary>
    public event Action? RulesChanged;

    public IReadOnlyCollection<string> ErroneousModels
    {
        get
        {
            lock (_sync)
                return _erroneous.ToList();
        }
    }

    public void SetData(ModelMatchingData data) => Data = data;

    /// <summary>模拟器拒绝生成这个模型（SIMCONNECT_EXCEPTION_CREATE_OBJECT_FAILED）。</summary>
    /// <returns>是不是第一次拉黑这个模型。</returns>
    public bool MarkErroneous(string model)
    {
        lock (_sync)
        {
            if (!_erroneous.Add(model))
                return false;
        }
        Log.Warning($"model {model} could not be created by the simulator and will not be used again");
        return true;
    }

    public void ClearErroneous(IEnumerable<string>? keep = null)
    {
        lock (_sync)
        {
            _erroneous.Clear();
            if (keep is not null)
                _erroneous.UnionWith(keep);
        }
    }

    public bool IsErroneous(string model)
    {
        lock (_sync)
            return _erroneous.Contains(model);
    }

    /// <summary>这个 title 能不能生成：扫描到了、或者是 2024 的被动 AI 机。</summary>
    public bool IsInstalled(string title) =>
        _installedTitles.Contains(title) || (Simulator == SimulatorType.Msfs2024 && Msfs2024PassiveAircraft.Contains(title));

    public int InstalledModelCount => _installedTitles.Count;

    /// <summary>换了模拟器：默认模型和内置规则跟着换。</summary>
    public void SetSimulator(SimulatorType simulator)
    {
        Simulator = simulator;
    }

    /// <summary>读自定义规则集，顺序就是优先级。读不了的文件跳过，原因记在 <see cref="RuleSetStatus"/>。</summary>
    public void LoadCustomRuleSets(IEnumerable<string> paths, bool raise = true)
    {
        var rules = new List<ModelMatchRule>();
        var status = new List<RuleSetStatus>();
        foreach (var path in paths)
        {
            try
            {
                var set = ModelMatchRuleSet.Load(path);
                rules.AddRange(set);
                status.Add(new RuleSetStatus(path, set.Count, null));
                Log.Info($"loaded {set.Count} rules from {path}");
            }
            catch (Exception e)
            {
                status.Add(new RuleSetStatus(path, 0, e.Message));
                Log.Warning($"could not load the rule set {path}: {e.Message}");
            }
        }
        _customRules = rules;
        _ruleSetStatus = status;
        Log.Info("Custom model matching rules loaded.");
        if (raise)
            RulesChanged?.Invoke();
    }

    /// <summary>
    /// 从扫描结果生成规则，vPilot Method_06000652。每个包里的涂装按 (机型, 航司) 归组，一组一条规则，
    /// 组内的涂装用 // 连起来随机挑；同一航司的所有涂装再出一条 TypeCode=ZZZZ 的规则。最后接上内置规则。
    /// </summary>
    public void GenerateRules(ModelScanResult? scan, bool raise = true)
    {
        var generated = new List<ModelMatchRule>();
        var installed = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var byAirline = new Dictionary<string, List<string>>(StringComparer.Ordinal);

        if (scan is not null)
        {
            foreach (var model in scan.AllModels())
            {
                if (!string.IsNullOrEmpty(model.Title))
                    installed.Add(model.Title);
            }

            foreach (var folder in scan.Folders.Where(f => !f.IsExcluded).OrderBy(f => f.Priority))
            {
                if (folder.RelativePath.Contains("carenado", StringComparison.OrdinalIgnoreCase))
                    continue;
                // 机型 → 航司 → 涂装，保持插入顺序
                var groups = new Dictionary<string, Dictionary<string, List<string>>>(StringComparer.Ordinal);
                foreach (var subfolder in folder.Subfolders.Where(s => !s.IsExcluded))
                {
                    if (subfolder.RelativePath.Contains("carenado", StringComparison.OrdinalIgnoreCase))
                        continue;
                    foreach (var model in subfolder.Models.Where(m => !m.IsExcluded))
                    {
                        if (string.IsNullOrEmpty(model.Title) || model.Status == ModelStatus.Ignored)
                            continue;
                        IReadOnlyList<ModelSpec> specs = Data.SpecsForTitle(model.Title);
                        if (specs.Count == 0)
                            specs = ModelSpecDeriver.Derive(model, Data);
                        foreach (var spec in specs)
                        {
                            var prefix = spec.CallsignPrefix ?? "";
                            if (!groups.TryGetValue(spec.TypeCode, out var airlines))
                                groups[spec.TypeCode] = airlines = new Dictionary<string, List<string>>(StringComparer.Ordinal);
                            if (!airlines.TryGetValue(prefix, out var titles))
                                airlines[prefix] = titles = new List<string>();
                            titles.Add(spec.Title);
                            if (prefix.Length > 0)
                            {
                                if (!byAirline.TryGetValue(prefix, out var all))
                                    byAirline[prefix] = all = new List<string>();
                                all.Add(spec.Title);
                            }
                        }
                    }
                }
                foreach (var (typeCode, airlines) in groups)
                foreach (var (prefix, titles) in airlines)
                {
                    generated.Add(new ModelMatchRule
                    {
                        TypeCode = typeCode,
                        CallsignPrefix = prefix,
                        ModelName = string.Join(ModelMatchRule.ModelDelimiter, titles),
                        SourceFilePath = ModelMatchRule.AutoGenerated
                    });
                }
            }
        }

        foreach (var (prefix, titles) in byAirline)
        {
            generated.Add(new ModelMatchRule
            {
                TypeCode = "ZZZZ",
                CallsignPrefix = prefix,
                ModelName = string.Join(ModelMatchRule.ModelDelimiter, titles),
                SourceFilePath = ModelMatchRule.AutoGenerated
            });
        }

        // FSX / P3D 没有内置规则（vPilot 也一样），全靠扫描出来的模型
        var builtIn = Simulator switch
        {
            SimulatorType.Msfs2024 => BuiltInRules.Msfs2024,
            _ when Simulator.IsLegacy() => [],
            _ => BuiltInRules.Msfs2020
        };
        foreach (var (typeCode, modelName) in builtIn)
        {
            generated.Add(new ModelMatchRule
            {
                TypeCode = typeCode,
                ModelName = modelName,
                SourceFilePath = BuiltInSource
            });
        }

        _installedTitles = installed;
        _generatedRules = generated;
        Log.Info($"Model matching rules generated: {generated.Count} rules from {installed.Count} installed models.");
        if (raise)
            RulesChanged?.Invoke();
    }

    public void RaiseRulesChanged() => RulesChanged?.Invoke();

    /// <summary>
    /// 网络上报的机型 → ICAO 机型码。认得 "B738"、"B738/M"、"H/B744/L" 这几种写法，再查别名表。
    /// 认不出来返回 "ZZZZ"——这样至少还能按航司挑一架同航司的飞机。
    /// </summary>
    public string NormaliseTypeCode(string? equipment)
    {
        var text = (equipment ?? "").Trim().ToUpperInvariant();
        if (text.Length == 0)
            return "ZZZZ";
        var parts = text.Split('/', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
        var code = parts.FirstOrDefault(p => p.Length >= 2 && p.Length <= 4 && p.All(char.IsAsciiLetterOrDigit))
                   ?? parts.FirstOrDefault() ?? text;
        return Data.ResolveAlias(code) ?? code;
    }

    /// <summary>
    /// 给一架飞机挑模型，vPilot 的 fu()。
    /// </summary>
    /// <param name="callsign">呼号，航司前缀和航班号从这里取。</param>
    /// <param name="typeCode">机型码（已经 <see cref="NormaliseTypeCode"/> 过的或原样的都行）。</param>
    /// <param name="previousModel">上次给这架飞机挑中的模型；还在候选里就继续用它，免得换来换去。</param>
    public ModelMatchResult Match(string callsign, string? typeCode, string? previousModel = null)
    {
        callsign = (callsign ?? "").Trim().ToUpperInvariant();
        var type = NormaliseTypeCode(typeCode);
        var match = FlightNumber.Match(callsign);
        var flightNumber = match.Success && int.TryParse(match.Groups[1].Value, out var n) ? n : 0;

        var custom = _customRules;
        var generated = _generatedRules;
        var filterInstalled = _installedTitles.Count > 0;
        Data.TryGetSimilar(type, out var similar);

        for (var pass = 1; pass <= 4; pass++)
        {
            foreach (var rule in custom.Concat(generated))
            {
                var generic = !rule.IsCallsignSpecific;
                if (generic && pass <= 2)
                    continue;
                if (!generic && pass >= 3)
                    continue;
                if (!string.IsNullOrEmpty(rule.Callsign) && callsign != rule.Callsign)
                    continue;
                if (!string.IsNullOrEmpty(rule.CallsignPrefix) && !callsign.StartsWith(rule.CallsignPrefix, StringComparison.Ordinal))
                    continue;
                if (!string.IsNullOrEmpty(rule.TypeCode))
                {
                    if (pass is 1 or 3)
                    {
                        if (type != rule.TypeCode)
                            continue;
                    }
                    else if (similar.Count == 0 || !similar.Contains(rule.TypeCode))
                        continue;
                }
                if ((rule.MinFlightNumber != 0 && flightNumber < rule.MinFlightNumber)
                    || (rule.MaxFlightNumber != 0 && flightNumber == 0)
                    || (rule.MaxFlightNumber != 0 && flightNumber > rule.MaxFlightNumber))
                    continue;

                var isCustom = rule.SourceFilePath != ModelMatchRule.AutoGenerated && rule.SourceFilePath != BuiltInSource;
                var candidates = rule.Models()
                    .Where(m => !IsErroneous(m))
                    // 自定义规则集里引用的模型不一定装了（规则集比包新、或只装了一部分），
                    // 装了的才用，否则模拟器建不出来，又要绕一圈拉黑再重配。
                    .Where(m => !isCustom || !filterInstalled || IsInstalled(m))
                    .ToArray();
                if (candidates.Length == 0)
                    continue;

                string chosen;
                if (candidates.Length > 1)
                {
                    chosen = !string.IsNullOrEmpty(previousModel) && candidates.Contains(previousModel, StringComparer.OrdinalIgnoreCase)
                        ? previousModel
                        : candidates[Random.Shared.Next(candidates.Length)];
                }
                else
                    chosen = candidates[0];
                return new ModelMatchResult(chosen, rule, pass, type);
            }
        }

        return new ModelMatchResult(DefaultModel, null, 0, type);
    }
}
