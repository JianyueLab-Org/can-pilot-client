    private static readonly Dictionary<int, int[]> EvdevByVk = Table
        .GroupBy(e => e.Vk).ToDictionary(g => g.Key, g => g.Select(e => e.Evdev).ToArray());

    private static readonly Dictionary<int, int[]> MacByVk = Table.Where(e => e.Mac >= 0)
        .GroupBy(e => e.Vk).ToDictionary(g => g.Key, g => g.Select(e => e.Mac).ToArray());

    /// <summary>虚拟键码对应的 evdev 键码（可能不止一个，比如两个回车）。没有对应返回空。</summary>
    public static int[] Evdev(int vk) => EvdevByVk.TryGetValue(vk, out var codes) ? codes : [];

    /// <summary>虚拟键码对应的 macOS 键码。没有对应返回空。</summary>
    public static int[] Mac(int vk) => MacByVk.TryGetValue(vk, out var codes) ? codes : [];
